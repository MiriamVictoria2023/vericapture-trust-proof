import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import type { Database } from '@/integrations/supabase/types';

type EvidenceRow = Database['public']['Tables']['evidence_records']['Row'];
type CustodyRow = Database['public']['Tables']['custody_log']['Row'];

/**
 * Generate a PDF report for an evidence record's chain of custody.
 */
export function generateCustodyPDF(
  evidence: EvidenceRow,
  custodyLog: CustodyRow[],
  caseCode: string
) {
  const doc = new jsPDF();
  const pageWidth = doc.internal.pageSize.getWidth();

  // Header
  doc.setFillColor(15, 23, 42); // Deep Navy
  doc.rect(0, 0, pageWidth, 40, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(18);
  doc.setFont('helvetica', 'bold');
  doc.text('VeriCapture', 14, 18);
  doc.setFontSize(9);
  doc.setFont('helvetica', 'normal');
  doc.text('Zero-Trust Secure Evidence System — Chain of Custody Report', 14, 26);
  doc.text(`Generated: ${new Date().toLocaleString()}`, 14, 33);

  // Classification banner
  doc.setFillColor(37, 99, 235); // Emergency Blue
  doc.rect(0, 40, pageWidth, 8, 'F');
  doc.setFontSize(8);
  doc.setFont('helvetica', 'bold');
  doc.text('OFFICIAL — CHAIN OF CUSTODY DOCUMENT', pageWidth / 2, 45.5, { align: 'center' });

  // Evidence Details Section
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text('Evidence Details', 14, 58);

  doc.setDrawColor(200, 200, 200);
  doc.line(14, 60, pageWidth - 14, 60);

  const detailsData = [
    ['File Name', evidence.file_name],
    ['Case ID', caseCode],
    ['SHA-256 Hash', evidence.sha256_hash],
    ['File Type', evidence.file_type],
    ['File Size', `${(evidence.file_size / 1024).toFixed(1)} KB`],
    ['Status', evidence.status.toUpperCase()],
    ['Captured At', new Date(evidence.created_at).toLocaleString()],
    ['Coordinates', evidence.geo_lat && evidence.geo_lng ? `${evidence.geo_lat.toFixed(6)}, ${evidence.geo_lng.toFixed(6)}` : 'N/A'],
    ['Device Info', (evidence.device_info || 'N/A').substring(0, 60)],
    ['Notary Block #', evidence.block_index?.toString() || 'N/A'],
    ['Notary Hash', (evidence.notary_hash || 'N/A').substring(0, 64)],
  ];

  autoTable(doc, {
    startY: 64,
    head: [],
    body: detailsData,
    theme: 'plain',
    styles: { fontSize: 8, cellPadding: 2 },
    columnStyles: {
      0: { fontStyle: 'bold', cellWidth: 40, textColor: [100, 116, 139] },
      1: { cellWidth: 'auto', font: 'courier' },
    },
    margin: { left: 14, right: 14 },
  });

  // Chain of Custody Log
  const currentY = (doc as any).lastAutoTable?.finalY || 130;

  doc.setTextColor(15, 23, 42);
  doc.setFontSize(12);
  doc.setFont('helvetica', 'bold');
  doc.text('Chain of Custody Log', 14, currentY + 12);

  doc.setDrawColor(200, 200, 200);
  doc.line(14, currentY + 14, pageWidth - 14, currentY + 14);

  if (custodyLog.length > 0) {
    autoTable(doc, {
      startY: currentY + 18,
      head: [['#', 'Timestamp', 'Action', 'Actor', 'IP Address', 'Details']],
      body: custodyLog.map((entry, i) => [
        (i + 1).toString(),
        new Date(entry.created_at).toLocaleString(),
        entry.action.toUpperCase(),
        entry.actor,
        entry.ip_address,
        (entry.details || '').substring(0, 40),
      ]),
      theme: 'grid',
      styles: { fontSize: 7, cellPadding: 2 },
      headStyles: { fillColor: [15, 23, 42], textColor: [255, 255, 255], fontStyle: 'bold' },
      alternateRowStyles: { fillColor: [241, 245, 249] },
      margin: { left: 14, right: 14 },
    });
  } else {
    doc.setFontSize(9);
    doc.setFont('helvetica', 'italic');
    doc.setTextColor(100, 116, 139);
    doc.text('No custody log entries recorded.', 14, currentY + 22);
  }

  // Footer
  const finalY = (doc as any).lastAutoTable?.finalY || currentY + 30;
  doc.setDrawColor(200, 200, 200);
  doc.line(14, finalY + 10, pageWidth - 14, finalY + 10);
  doc.setFontSize(7);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(148, 163, 184);
  doc.text('This document is an official chain of custody record generated by VeriCapture.', 14, finalY + 16);
  doc.text('Any tampering with this document will invalidate the chain of custody.', 14, finalY + 21);
  doc.text(`Document integrity hash: Report generated at ${new Date().toISOString()}`, 14, finalY + 26);

  // Save
  doc.save(`VeriCapture_CoC_${evidence.file_name.replace(/[^a-zA-Z0-9]/g, '_')}.pdf`);
}
